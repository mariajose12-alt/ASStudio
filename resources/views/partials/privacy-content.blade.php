        <li>Gestionar reservas, calendario de sesiones y disponibilidad</li>
        <li>Procesar y confirmar pagos, incluyendo la validación de comprobantes</li>
        <li>Entregar tus fotografías a través de tu galería privada</li>
        <li>Enviarte notificaciones sobre el estado de tu reserva, pago o galería,
