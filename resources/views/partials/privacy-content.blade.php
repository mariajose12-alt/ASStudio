        judicial, o para proteger los derechos, propiedad o seguridad de Abrahan Sánchez,
        nuestros usuarios, o el público.
    </p>

    <h2>4. Fotografías de menores de edad</h2>
    <p>
        Nuestras sesiones fotográficas pueden incluir menores de edad (por ejemplo,
        sesiones familiares, bautizos, cumpleaños). En estos casos, el adulto que
        realiza la reserva declara ser el padre, madre o tutor legal del menor, o
        contar con la autorización correspondiente, y otorga su consentimiento para
        que dichas imágenes sean captadas, almacenadas y entregadas a través de la
        plataforma. No recolectamos ni solicitamos directamente datos personales de
        menores de edad sin la intervención y consentimiento de un adulto responsable.
    </p>

    <h2>5. Cuánto tiempo conservamos tu información</h2>
    <p>
        Conservamos tu información personal mientras mantengas una cuenta activa
        en la plataforma, o durante el tiempo necesario para cumplir con obligaciones
        legales, fiscales o contractuales. Las fotografías de tu sesión se conservan
        según el plan o acuerdo específico de tu contrato de servicio con Abraham Sánchez.
        Podés solicitar la eliminación de tu cuenta y datos en cualquier momento,
        sujeto a las excepciones legales aplicables (por ejemplo, comprobantes
        fiscales que debamos conservar por ley).
    </p>

    <h2>6. Cómo protegemos tu información</h2>
    <p>
        Implementamos medidas técnicas y organizativas razonables para proteger tu
        información personal, incluyendo cifrado de contraseñas, acceso restringido
        a los sistemas de almacenamiento, y URLs firmadas y temporales para el acceso
        a tus fotografías. Sin embargo, ningún sistema de transmisión o almacenamiento
        de datos es 100% seguro, por lo que no podemos garantizar la seguridad
        absoluta de tu información.
    </p>

