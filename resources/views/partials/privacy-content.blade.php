    <ul>
        <li>Nombre completo</li>
        <li>Correo electrónico</li>
        <li>Número de teléfono (incluyendo WhatsApp)</li>
        <li>Contraseña (almacenada de forma cifrada)</li>
        <li>Dirección, cuando aplica a la sesión reservada</li>
        <li>Comprobantes de pago y datos asociados a la transacción</li>
        <li>Preferencias de contacto y notificación</li>
    </ul>

    <h3>1.2 Fotografías e imágenes</h3>
    <p>
        Como parte del servicio, procesamos y almacenamos las <strong>fotografías
            tomadas durante tu sesión</strong>, incluyendo imágenes en las que podés
        aparecer vos y, en su caso, otras personas presentes en la sesión (familiares,
        invitados, menores de edad bajo tu responsabilidad). Estas imágenes se
        almacenan de forma segura y se comparten con vos exclusivamente a través
        de tu galería privada dentro de la plataforma.
    </p>

    <h3>1.3 Información recolectada automáticamente</h3>
    <ul>
        <li>Dirección IP y datos básicos de navegación</li>
        <li>Fecha y hora de acceso a la plataforma</li>
        <li>Estado de lectura de notificaciones dentro de la app</li>
    </ul>

