        <li>
            <strong>Google (OAuth):</strong> si elegís iniciar sesión con tu cuenta
            de Google.
        </li>
        <li>
            <strong>Proveedores de correo electrónico:</strong> envío de notificaciones
            y comunicaciones transaccionales.
        </li>
    </ul>
